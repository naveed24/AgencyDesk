-- AgencyDesk database schema (PostgreSQL 14+). Fresh database only.
-- Every tenant-owned child has agency_id plus composite FKs to prevent
-- pointing at data that belongs to another agency.

CREATE TABLE public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT normalized_email CHECK (email = lower(email))
);

CREATE TABLE public.agencies (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.agency_memberships (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    agency_id BIGINT NOT NULL REFERENCES public.agencies(id),
    user_id BIGINT NOT NULL REFERENCES public.users(id),
    role VARCHAR(30) NOT NULL CHECK (role IN ('agency_admin','agency_member','client_user')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT unique_user_agency UNIQUE (user_id, agency_id),
    CONSTRAINT unique_agency_user UNIQUE (agency_id, user_id)
);

CREATE TABLE public.clients (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    agency_id BIGINT NOT NULL REFERENCES public.agencies(id),
    name VARCHAR(150) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT unique_client_id_agency UNIQUE (id,agency_id),
    CONSTRAINT unique_agency_client UNIQUE (agency_id,id)
);

CREATE TABLE public.client_memberships (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    agency_id BIGINT NOT NULL,
    client_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    FOREIGN KEY (agency_id,client_id) REFERENCES public.clients(agency_id,id),
    FOREIGN KEY (agency_id,user_id) REFERENCES public.agency_memberships(agency_id,user_id),
    CONSTRAINT unique_client_membership UNIQUE (agency_id,client_id,user_id)
);

CREATE TABLE public.projects (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    agency_id BIGINT NOT NULL REFERENCES public.agencies(id),
    client_id BIGINT NOT NULL,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active','completed','archived')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (agency_id,client_id) REFERENCES public.clients(agency_id,id),
    CONSTRAINT unique_project_id_agency UNIQUE (id,agency_id),
    CONSTRAINT unique_agency_project UNIQUE (agency_id,id)
);

CREATE TABLE public.project_members (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    agency_id BIGINT NOT NULL,
    project_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    FOREIGN KEY (agency_id,project_id) REFERENCES public.projects(agency_id,id),
    FOREIGN KEY (agency_id,user_id) REFERENCES public.agency_memberships(agency_id,user_id),
    CONSTRAINT unique_project_member UNIQUE (agency_id,project_id,user_id)
);

CREATE TABLE public.tasks (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    agency_id BIGINT NOT NULL,
    project_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL CHECK (length(trim(title)) > 0),
    description TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'todo'
        CHECK (status IN ('todo','in_progress','review','done')),
    priority VARCHAR(20) NOT NULL DEFAULT 'medium'
        CHECK (priority IN ('low','medium','high','urgent')),
    assignee_user_id BIGINT,
    due_date DATE,
    is_client_visible BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (agency_id,project_id) REFERENCES public.projects(agency_id,id),
    FOREIGN KEY (agency_id,project_id,assignee_user_id)
       REFERENCES public.project_members(agency_id,project_id,user_id),
    CONSTRAINT unique_task_id_agency UNIQUE (id,agency_id),
    CONSTRAINT unique_agency_task UNIQUE (agency_id,id)
);

CREATE TABLE public.comments (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    agency_id BIGINT NOT NULL,
    task_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    content TEXT NOT NULL CHECK (length(trim(content)) > 0),
    is_client_visible BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (agency_id,task_id) REFERENCES public.tasks(agency_id,id),
    FOREIGN KEY (agency_id,user_id) REFERENCES public.agency_memberships(agency_id,user_id)
);

CREATE TABLE public.time_entries (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    agency_id BIGINT NOT NULL,
    task_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    duration_minutes INTEGER NOT NULL CHECK (duration_minutes BETWEEN 1 AND 1440),
    note TEXT,
    entry_date DATE NOT NULL DEFAULT CURRENT_DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (agency_id,task_id) REFERENCES public.tasks(agency_id,id),
    FOREIGN KEY (agency_id,user_id) REFERENCES public.agency_memberships(agency_id,user_id)
);

CREATE TABLE public.task_files (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    agency_id BIGINT NOT NULL,
    task_id BIGINT NOT NULL,
    uploaded_by_user_id BIGINT NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    storage_path TEXT NOT NULL UNIQUE,
    content_type VARCHAR(150),
    is_client_visible BOOLEAN NOT NULL DEFAULT FALSE,
    approval_status VARCHAR(30) NOT NULL DEFAULT 'pending'
        CHECK (approval_status IN ('pending','approved','needs_changes')),
    reviewed_by_user_id BIGINT,
    reviewed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (agency_id,task_id) REFERENCES public.tasks(agency_id,id),
    FOREIGN KEY (agency_id,uploaded_by_user_id)
       REFERENCES public.agency_memberships(agency_id,user_id),
    FOREIGN KEY (agency_id,reviewed_by_user_id)
       REFERENCES public.agency_memberships(agency_id,user_id)
);

CREATE TABLE public.invitations (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    agency_id BIGINT NOT NULL REFERENCES public.agencies(id),
    client_id BIGINT,
    email VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL CHECK (role IN ('agency_admin','agency_member','client_user')),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending','accepted','revoked')),
    expires_at TIMESTAMPTZ NOT NULL,
    accepted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (agency_id,client_id) REFERENCES public.clients(agency_id,id),
    CONSTRAINT invite_client_role_check CHECK (
        (role='client_user' AND client_id IS NOT NULL)
        OR (role<>'client_user' AND client_id IS NULL)
    )
);

CREATE UNIQUE INDEX unique_pending_agency_invite
    ON public.invitations (agency_id,lower(email)) WHERE status='pending';
CREATE INDEX idx_projects_agency_client ON public.projects (agency_id,client_id);
CREATE INDEX idx_tasks_agency_project_status ON public.tasks (agency_id,project_id,status);
CREATE INDEX idx_comments_agency_task ON public.comments (agency_id,task_id,created_at);
CREATE INDEX idx_time_entries_agency_task ON public.time_entries (agency_id,task_id);
CREATE INDEX idx_files_agency_task ON public.task_files (agency_id,task_id);
CREATE INDEX idx_project_members_user_project ON public.project_members (agency_id,user_id,project_id);
CREATE INDEX idx_client_memberships_user_client ON public.client_memberships (agency_id,user_id,client_id);

-- Database guardrail: only client_user memberships can be linked to clients.
CREATE FUNCTION public.assert_client_member_role() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.agency_memberships m
     WHERE m.agency_id=NEW.agency_id AND m.user_id=NEW.user_id
       AND m.role='client_user') THEN
    RAISE EXCEPTION 'Client member must have the client_user role';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER check_client_member_role BEFORE INSERT OR UPDATE
ON public.client_memberships FOR EACH ROW EXECUTE FUNCTION public.assert_client_member_role();

-- Database guardrail: clients cannot be assigned as agency project staff.
CREATE FUNCTION public.assert_project_staff_role() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.agency_memberships m
     WHERE m.agency_id=NEW.agency_id AND m.user_id=NEW.user_id
       AND m.role IN ('agency_admin','agency_member')) THEN
    RAISE EXCEPTION 'Project member must be agency staff';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER check_project_staff_role BEFORE INSERT OR UPDATE
ON public.project_members FOR EACH ROW EXECUTE FUNCTION public.assert_project_staff_role();
